export function toMbartCode(iso639: string): string | null {
  return MBART_MAP[iso639] ?? null;
}

export function canTranslateBetween(sourceLang: string, targetLang: string): boolean {
  if (sourceLang === targetLang) return true;
  return toMbartCode(sourceLang) !== null && toMbartCode(targetLang) !== null;
}
